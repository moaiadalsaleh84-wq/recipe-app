// Writes src/components/mascot/foxImages.ts from the PNGs in assets/mascot/:
//   fox-<pose>.png (the pose) and fox-<pose>-blink.png (closed eyes, optional).
// Run after adding or renaming fox images:  node scripts/fox-images.mjs
import { readdirSync, writeFileSync, existsSync } from 'node:fs';

const dir = 'assets/mascot';
const poses = ['idle', 'happy', 'wave', 'reading', 'oops', 'chef', 'alert', 'cheer', 'sleepy'];
const files = existsSync(dir) ? readdirSync(dir) : [];
const line = (pose, file) => `  ${pose}: require('../../../${dir}/${file}'),`;
const images = poses.filter((p) => files.includes(`fox-${p}.png`)).map((p) => line(p, `fox-${p}.png`));
const blinks = poses.filter((p) => files.includes(`fox-${p}-blink.png`)).map((p) => line(p, `fox-${p}-blink.png`));
const unknown = files.filter((f) => f.endsWith('.png') && !poses.some((p) => f === `fox-${p}.png` || f === `fox-${p}-blink.png`));

writeFileSync(
  'src/components/mascot/foxImages.ts',
  `/**
 * The fox's artwork: pose → image (transparent PNG), plus an optional closed-eye frame for blinking.
 * Generated by \`node scripts/fox-images.mjs\` from the files in assets/mascot/:
 *   fox-<pose>.png          the pose (e.g. fox-happy.png)
 *   fox-<pose>-blink.png    the same pose with closed eyes (optional)
 * Poses without a file use the drawn fox (FoxArt) until the image arrives.
 */
import type { FoxPose } from './foxPoses';

export const FOX_IMAGES: Partial<Record<FoxPose, number>> = {${images.length ? `\n${images.join('\n')}\n` : ''}};
export const FOX_BLINK_IMAGES: Partial<Record<FoxPose, number>> = {${blinks.length ? `\n${blinks.join('\n')}\n` : ''}};
`,
);
console.log(`fox images: ${images.length} poses, ${blinks.length} blink frames`);
if (unknown.length) console.log(`not used (name them fox-<pose>.png, poses: ${poses.join(', ')}):`, unknown.join(', '));
